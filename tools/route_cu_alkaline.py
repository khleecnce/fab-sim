"""2×2 격자의 빈 칸을 문헌에서 채울 수 없을 때 — 다른 경로로 결론에 도달한다.

상황
────
구리 알칼리 가지의 k 가 'pH 구간' 때문인지 '억제제 유무' 때문인지 분리하려면
2×2 격자가 필요한데, 대각선 2칸만 차 있다:

    산성  / 억제제 유 : k = 0.1428   (US20080090500A1, 12점)
    알칼리 / 억제제 무 : k = 0.3329   (US9200180B2 T4, 5점, R²=0.9971)
    산성  / 억제제 무 : (없음)
    알칼리 / 억제제 유 : (없음)

특허 108건 전문을 검증된 파서로 훑어 pH 스윕 계열을 찾았으나 쓸 수 있는
추가 계열이 나오지 않았다(유일한 후보는 제거율이 1~3 Å/min 인 결함 억제
지표라 MRR 이 아니었다).

"문헌에 없다"에서 멈추지 않는다 — 탈출 경로를 적용한다
───────────────────────────────────────────────────
sim/unknown_router.py 의 경로 중 이 문제에 적용 가능한 것:

  R2 부등식   : 두 축의 기여를 각각 확정하지 못해도 **부호와 상한**은 정할 수 있다.
  R7 구조적제거: 분리 불가능한 두 축을 **하나의 레짐 좌표**로 묶어 자유
                파라미터를 늘리지 않는다.
  R8 측정명세 : 남는 미지량은 "이렇게 재 오시오"로 제품 기능화한다.

이 파일은 R2 를 실행한다: 두 계열이 공유하는 물리(산화제 매개 Nernst)에서
**k 의 하한**을 유도하고, 관측된 두 k 가 그 하한과 어떤 관계인지 본다.

⚠ 판정 기준에 물질명을 넣지 않는다. 기준은
  "이 계에서 pH 가 제거율에 들어오는 경로가 몇 개인가" 하나다.
"""
import math
import sys
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

R = 8.314462618
F = 96485.33212
T = 298.15
NERNST_MV = 2.303 * R * T / F * 1000.0        # 59.16 mV/pH


def main() -> int:
    print("=" * 84)
    print("R2 부등식 — 두 축을 분리하지 못해도 확정되는 것")
    print("=" * 84)

    k_acid, n_acid = 0.1428, 12
    k_alk, n_alk = 0.3329, 5
    print(f"""
관측
  산성  / 억제제 유 : k = {k_acid:.4f} /pH   (n={n_acid})
  알칼리 / 억제제 무 : k = {k_alk:.4f} /pH   (n={n_alk})
  비                : {k_alk / k_acid:.2f} 배
""")

    print("-" * 84)
    print("① pH 가 들어오는 경로를 센다 (물질명 없이)")
    print("""
  경로 A — 산화제의 환원 전위 (Nernst)
      산화제 반쪽반응에 H⁺ 가 있으면 dE/dpH = -59.16 mV/pH.
      이 경로는 **산화제가 있는 모든 계에 공통**이다.

  경로 B — 금속 표면의 부동태 안정영역
      pH 가 오르면 산화물/수산화물이 안정해져 막이 두꺼워진다.
      이 경로는 **억제제가 표면을 이미 덮고 있으면 한계효과가 작다**
      (덮인 자리에 추가로 덮을 여지가 없다).

  경로 C — 억제제 자신의 흡착 평형
      억제제가 있어야만 존재한다. 없으면 이 경로는 0 이다.
""")

    print("-" * 84)
    print("② 부등식이 말해주는 것")
    print(f"""
  억제제가 **없는** 계: 경로 A + B  (C 없음)
  억제제가 **있는** 계: 경로 A + B' + C,  단 B' < B  (위 이유로 한계효과 감소)

  두 계가 공유하는 것은 A 뿐이고, 억제제가 있는 쪽은 B 가 눌린다.
  따라서 **다른 조건이 같다면**  k(억제제 무) > k(억제제 유)  이어야 한다.

  관측: {k_alk:.4f} > {k_acid:.4f}  ✅ 부등식과 **모순되지 않는다**

  ⚠ 그러나 이것은 확증이 아니다. 두 계열은 pH 구간도 다르므로
    부등식이 맞는 것만으로 '억제제가 원인'이라고 말할 수 없다.
    확정되는 것은 **부호**뿐이다:
        억제제는 pH 민감도를 **낮추는 방향**으로 작용한다.
""")

    print("-" * 84)
    print("③ 그래서 무엇을 구현할 수 있는가 (R7 구조적 제거)")
    print(f"""
  ❌ 하면 안 되는 것
     k_alkaline = {k_alk:.4f} 를 알칼리 계수로 박아 넣기.
     → pH 효과와 억제제 효과가 한 계수에 뭉친다. 억제제가 있는
       알칼리 조성이 오면 과대 예측한다(그 계열이 실제로 검증셋에 있다).

  ✅ 할 수 있는 것
     두 축을 **하나의 레짐 좌표**로 선언한다 — 자유 파라미터를 늘리지 않고,
     각 레짐이 자기 데이터에서만 계수를 갖는다:

         레짐 1 (산성 · 억제제 유) : k = {k_acid:.4f}   [literature]
         레짐 2 (알칼리 · 억제제 무) : k = {k_alk:.4f}   [literature]
         레짐 3 (산성 · 억제제 무)  : 미관측 → 항 비활성 + 신고
         레짐 4 (알칼리 · 억제제 유) : 미관측 → 항 비활성 + 신고

     핵심: 레짐 3·4 에 값을 **넣지 않는다.** 그 조건이 들어오면 모델은
     "이 레짐은 관측이 없다"고 신고하고 순위만 예측한다.
     이것이 '조용히 틀린 숫자'보다 낫다.

  ⚠ 이 설계는 자유도를 늘리지 않는다: 계수 2개가 각각 자기 데이터
    12점·5점에서 나왔고, 레짐 판정은 데이터가 아니라 **조건**(pH 골 위치,
    억제제 선언 유무)이 한다.
""")

    print("-" * 84)
    print("④ R8 — 남는 미지량의 측정 명세")
    print(f"""
  레짐 3·4 를 채우려면 필요한 것은 딱 하나다:

     같은 조성에서 억제제만 빼거나 넣고 pH 를 3 점 이상 스윕한 제거율 표.

  · 한 계열 안에서 억제제 농도를 0 과 유효농도로 두 수준
  · 각 수준에서 pH 를 골(pH 6~6.5) 양쪽으로 최소 3 점
  · 나머지 조성·공정은 고정

  이 표 하나가 두 칸을 동시에 채운다. 문헌 탐색보다 **이 실험 하나가 싸다**
  — 그리고 이것이 제품이 사용자에게 돌려줄 수 있는 답이다.
""")

    nernst_k = NERNST_MV / 1000.0
    print("-" * 84)
    print(f"""참고: Nernst 상한 검산
  산화제 경로만으로 설명 가능한 최대 기울기는 전위 {NERNST_MV:.2f} mV/pH 에
  Tafel 기울기를 나눈 값이다. 전형 Tafel 0.06~0.12 V/decade 를 쓰면
  {nernst_k / 0.12:.3f} ~ {nernst_k / 0.06:.3f} decade/pH → k = {nernst_k / 0.12 * 2.303:.3f} ~ {nernst_k / 0.06 * 2.303:.3f} /pH.

  관측 k 는 둘 다 이 범위 **아래**다({k_acid:.4f}, {k_alk:.4f}).
  → 두 계 모두 순수 전하이동 지배가 아니라 혼합 지배이며, 이는
    노트(§6)가 이미 Tafel 검산 10배 어긋남으로 보고한 것과 일관된다.
  → 즉 k 를 Nernst 에서 유도할 수 없다는 사실이 **재확인**된다.
    함수형은 물리, 계수 크기는 실측 — 이 구분을 유지한다.
""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
